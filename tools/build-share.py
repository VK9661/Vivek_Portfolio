"""Builds the link previews and the per-project pages.

Apps such as WhatsApp, LinkedIn and X read the og: tags in a page's <head> and do not run
JavaScript, so every project needs its own static page with its own tags.

It writes:
  assets/img/share/portfolio.jpg   preview of the portfolio link, from tools/og.html
  assets/img/share/<id>.jpg        preview of each project, from tools/og.html?id=<id>
  project-<id>.html                project.html with that project's title, description and
                                   preview image in the head, and data-id on <body>
  sitemap.xml                      every page and project page

Run it from the repo root after adding a project or editing project.html:
  python tools/build-share.py
Add --pages to skip the image renders and only rewrite the HTML and sitemap.
"""
import html, json, os, pathlib, re, subprocess, sys, tempfile

from PIL import Image

TOOLS = pathlib.Path(__file__).resolve().parent
ROOT = TOOLS.parent
SHARE = ROOT / 'assets/img/share'
URL = 'https://vivek-portfolio-beta-eight.vercel.app/'
CHROME = r'C:\Program Files\Google\Chrome\Application\chrome.exe'
V = '4'  # bump when the preview images change, so apps fetch them again


def projects():
    js = (ROOT / 'assets/js/data.js').read_text(encoding='utf-8')
    out = subprocess.run(['node'], input='const window={};' + js + ';process.stdout.write(JSON.stringify(window.PROJECTS))',
                         capture_output=True, text=True, encoding='utf-8', check=True).stdout
    return json.loads(out)


def render(query, out):
    """Screenshot tools/og.html at 1200 x 630 with headless Chrome and save it as a JPG."""
    with tempfile.TemporaryDirectory() as tmp:
        png = os.path.join(tmp, 'shot.png')
        subprocess.run([CHROME, '--headless=new', '--disable-gpu', '--hide-scrollbars', '--allow-file-access-from-files',
                        '--virtual-time-budget=9000', '--window-size=1200,630', '--user-data-dir=' + os.path.join(tmp, 'profile'),
                        '--screenshot=' + png, (TOOLS / 'og.html').as_uri() + query], check=True, capture_output=True)
        Image.open(png).convert('RGB').save(out, quality=86, optimize=True, progressive=True)


def meta(page, key, value, attr='property'):
    v = html.escape(value, quote=True)
    pat = re.compile(r'(<meta %s="%s" content=")[^"]*(">)' % (attr, re.escape(key)))
    assert pat.search(page), key
    return pat.sub(lambda m: m.group(1) + v + m.group(2), page, count=1)


def main():
    P = projects()
    if '--pages' not in sys.argv:
        render('', SHARE / 'portfolio.jpg')
        for p in P:
            render('?id=' + p['id'], SHARE / (p['id'] + '.jpg'))
        print('previews:', len(P) + 1)

    tpl = (ROOT / 'project.html').read_text(encoding='utf-8')
    for p in P:
        title = f"{p['title']}: {p['kind']} | Vivek Kumar"
        desc = p.get('seo') or p['summary']
        url = f"{URL}project-{p['id']}.html"
        img = f"{URL}assets/img/share/{p['id']}.jpg?v={V}"
        s = tpl.replace('<meta name="robots" content="noindex">\n', '')
        s = re.sub(r'<title>[^<]*</title>', '<title>' + html.escape(title) + '</title>', s, count=1)
        s = meta(s, 'description', desc, 'name')
        s = re.sub(r'(<link rel="canonical" href=")[^"]*(">)', lambda m: m.group(1) + url + m.group(2), s, count=1)
        s = meta(s, 'og:type', 'article')
        s = meta(s, 'og:title', title)
        s = meta(s, 'og:description', p['summary'])
        s = meta(s, 'og:url', url)
        s = meta(s, 'og:image', img)
        s = meta(s, 'og:image:alt', f"{p['title']}, {p['kind']} by Vivek Kumar")
        s = meta(s, 'twitter:title', title, 'name')
        s = meta(s, 'twitter:description', p['summary'], 'name')
        s = meta(s, 'twitter:image', img, 'name')
        s = s.replace('<body data-page="project">', f'<body data-page="project" data-id="{p["id"]}">', 1)
        s = s.replace('<!doctype html>\n', '<!doctype html>\n<!-- Generated by tools/build-share.py from project.html. Edit project.html, then rerun the script. -->\n', 1)
        (ROOT / f"project-{p['id']}.html").write_text(s, encoding='utf-8', newline='\n')

    pages = ['', 'works.html', 'about.html', 'services.html', 'contact.html'] + [f"project-{p['id']}.html" for p in P]
    (ROOT / 'sitemap.xml').write_text('<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
                                      + ''.join(f'  <url><loc>{URL}{u}</loc></url>\n' for u in pages) + '</urlset>\n', encoding='utf-8', newline='\n')
    print('project pages:', len(P))


if __name__ == '__main__':
    main()
